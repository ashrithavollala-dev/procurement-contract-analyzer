-- V1: core schema for the Agentic Procurement Contract Analyzer.
-- Flyway owns the schema; Hibernate runs with ddl-auto=validate and PgVectorStore with
-- initialize-schema=false. Embedding dimension 384 = sentence-transformers/all-MiniLM-L6-v2.

CREATE EXTENSION IF NOT EXISTS vector;

-- ---------------------------------------------------------------------------
-- contracts
-- ---------------------------------------------------------------------------
CREATE TABLE contracts (
    id                UUID          PRIMARY KEY,
    title             VARCHAR(255)  NOT NULL,
    vendor_name       VARCHAR(255),
    original_filename VARCHAR(255)  NOT NULL,
    content_hash      VARCHAR(64)   NOT NULL,
    file_size_bytes   BIGINT        NOT NULL,
    page_count        INTEGER,
    chunk_count       INTEGER,
    status            VARCHAR(20)   NOT NULL,
    error_code        VARCHAR(40),
    error_message     VARCHAR(1000),
    stored_path       VARCHAR(500),
    processed_at      TIMESTAMPTZ,
    created_at        TIMESTAMPTZ   NOT NULL,
    updated_at        TIMESTAMPTZ   NOT NULL,
    version           BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_contracts_content_hash UNIQUE (content_hash),
    CONSTRAINT ck_contracts_status CHECK (status IN ('UPLOADED', 'QUEUED', 'PROCESSING', 'READY', 'FAILED')),
    CONSTRAINT ck_contracts_hash_format CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_contracts_file_size CHECK (file_size_bytes >= 0),
    CONSTRAINT ck_contracts_page_count CHECK (page_count IS NULL OR page_count >= 0),
    CONSTRAINT ck_contracts_chunk_count CHECK (chunk_count IS NULL OR chunk_count >= 0)
);

CREATE INDEX ix_contracts_status ON contracts (status);
CREATE INDEX ix_contracts_created_at ON contracts (created_at DESC);
-- Startup recovery scans in-flight rows by age.
CREATE INDEX ix_contracts_status_updated_at ON contracts (status, updated_at);

-- ---------------------------------------------------------------------------
-- compliance_rules
-- ---------------------------------------------------------------------------
CREATE TABLE compliance_rules (
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(64)   NOT NULL,
    title       VARCHAR(200)  NOT NULL,
    question    VARCHAR(2000) NOT NULL,
    guidance    VARCHAR(4000) NOT NULL,
    severity    VARCHAR(10)   NOT NULL,
    mandatory   BOOLEAN       NOT NULL,
    active      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ   NOT NULL,
    updated_at  TIMESTAMPTZ   NOT NULL,
    version     BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_compliance_rules_code UNIQUE (code),
    CONSTRAINT ck_compliance_rules_code_format CHECK (code ~ '^[A-Z][A-Z0-9_]{2,63}$'),
    CONSTRAINT ck_compliance_rules_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL'))
);

CREATE INDEX ix_compliance_rules_active ON compliance_rules (active);

-- ---------------------------------------------------------------------------
-- audit_runs (cascade-deleted with their contract)
-- ---------------------------------------------------------------------------
CREATE TABLE audit_runs (
    id               UUID          PRIMARY KEY,
    contract_id      UUID          NOT NULL,
    status           VARCHAR(20)   NOT NULL,
    total_rules      INTEGER       NOT NULL DEFAULT 0,
    completed_rules  INTEGER       NOT NULL DEFAULT 0,
    risk_score       NUMERIC(5, 1),
    risk_band        VARCHAR(10),
    summary          VARCHAR(2000),
    error_code       VARCHAR(40),
    started_at       TIMESTAMPTZ,
    completed_at     TIMESTAMPTZ,
    created_at       TIMESTAMPTZ   NOT NULL,
    updated_at       TIMESTAMPTZ   NOT NULL,
    version          BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT fk_audit_runs_contract FOREIGN KEY (contract_id) REFERENCES contracts (id) ON DELETE CASCADE,
    CONSTRAINT ck_audit_runs_status CHECK (status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_audit_runs_total_rules CHECK (total_rules >= 0),
    CONSTRAINT ck_audit_runs_completed_rules CHECK (completed_rules >= 0 AND completed_rules <= total_rules),
    CONSTRAINT ck_audit_runs_risk_score CHECK (risk_score IS NULL OR (risk_score >= 0 AND risk_score <= 100)),
    CONSTRAINT ck_audit_runs_risk_band CHECK (risk_band IS NULL OR risk_band IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL'))
);

CREATE INDEX ix_audit_runs_contract_created ON audit_runs (contract_id, created_at DESC);
CREATE INDEX ix_audit_runs_status_updated_at ON audit_runs (status, updated_at);
CREATE INDEX ix_audit_runs_created_at ON audit_runs (created_at DESC);

-- ---------------------------------------------------------------------------
-- audit_findings (cascade-deleted with their run; one finding per rule per run)
-- ---------------------------------------------------------------------------
CREATE TABLE audit_findings (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_run_id    UUID          NOT NULL,
    rule_id         BIGINT        NOT NULL,
    status          VARCHAR(20)   NOT NULL,
    confidence      NUMERIC(4, 3) NOT NULL,
    explanation     TEXT,
    evidence_quote  TEXT,
    evidence_page   INTEGER,
    recommendation  TEXT,
    iterations      INTEGER       NOT NULL DEFAULT 0,
    queries_used    TEXT,
    error_code      VARCHAR(40),
    created_at      TIMESTAMPTZ   NOT NULL,
    updated_at      TIMESTAMPTZ   NOT NULL,
    CONSTRAINT fk_audit_findings_run FOREIGN KEY (audit_run_id) REFERENCES audit_runs (id) ON DELETE CASCADE,
    CONSTRAINT fk_audit_findings_rule FOREIGN KEY (rule_id) REFERENCES compliance_rules (id) ON DELETE RESTRICT,
    CONSTRAINT uk_audit_findings_run_rule UNIQUE (audit_run_id, rule_id),
    CONSTRAINT ck_audit_findings_status CHECK (status IN ('COMPLIANT', 'PARTIAL', 'NON_COMPLIANT', 'NOT_FOUND', 'NEEDS_REVIEW')),
    CONSTRAINT ck_audit_findings_confidence CHECK (confidence >= 0 AND confidence <= 1),
    CONSTRAINT ck_audit_findings_evidence_page CHECK (evidence_page IS NULL OR evidence_page >= 1),
    CONSTRAINT ck_audit_findings_iterations CHECK (iterations >= 0)
);

CREATE INDEX ix_audit_findings_rule ON audit_findings (rule_id);
CREATE INDEX ix_audit_findings_status ON audit_findings (status);

-- ---------------------------------------------------------------------------
-- vector_store: layout required by Spring AI PgVectorStore (id uuid, content text,
-- metadata json/jsonb, embedding vector(N)). jsonb is used because PgVectorStore inserts
-- with ?::jsonb and filters with metadata::jsonb @@ jsonpath.
-- Metadata keys: contractId, page, chunkIndex, heading.
-- ---------------------------------------------------------------------------
CREATE TABLE vector_store (
    id         UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    content    TEXT,
    metadata   JSONB,
    embedding  VECTOR(384)
);

-- Approximate nearest-neighbour index for cosine distance (the <=> operator).
CREATE INDEX ix_vector_store_embedding_hnsw ON vector_store USING hnsw (embedding vector_cosine_ops);
-- Equality lookups by contract (native counts, deletes, admin queries).
CREATE INDEX ix_vector_store_contract_id ON vector_store ((metadata ->> 'contractId'));
-- Supports PgVectorStore's jsonpath filter (metadata @@ '$.contractId == "..."').
CREATE INDEX ix_vector_store_metadata_gin ON vector_store USING gin (metadata jsonb_path_ops);
